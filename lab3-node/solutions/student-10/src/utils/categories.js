// Порядок вывода категорий в списке покупок
export const CATEGORY_ORDER = [...Object.keys(CATEGORIES), OTHER_CATEGORY];

export const categorize = (name) => {
  const lower = name.toLowerCase();
  const found = Object.entries(CATEGORIES).find(
    ([, words]) => words.some((word) => lower.includes(word))
  );
  return found ? found[0] : OTHER_CATEGORY;
};